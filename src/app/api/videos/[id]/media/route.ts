import { createReadStream } from "node:fs";
import { stat } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import { getServerConfig } from "@/lib/server/config";
import { getDb } from "@/lib/server/db";
import { rejectNonLocal } from "@/lib/server/http";
import { parseRange, STORAGE_NAME_PATTERN } from "@/lib/server/media";
import { getVideo } from "@/lib/server/videos-repo";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

async function serve(request: Request, ctx: RouteContext<"/api/videos/[id]/media">, includeBody: boolean) {
  const rejected = rejectNonLocal(request);
  if (rejected) return rejected;
  const { id } = await ctx.params;
  const video = getVideo(getDb(), id);
  // Storage names are generated by us; the pattern check is a second guard against path tricks.
  if (!video || !STORAGE_NAME_PATTERN.test(video.storageName)) return new Response("Not found", { status: 404 });
  const filePath = path.join(getServerConfig().videosDir, video.storageName);
  const info = await stat(filePath).catch(() => null);
  if (!info?.isFile()) return new Response("The local video file is missing.", { status: 404 });

  const size = info.size;
  const baseHeaders: Record<string, string> = {
    "Accept-Ranges": "bytes",
    "Content-Type": video.mimeType ?? "application/octet-stream",
    "Cache-Control": "private, no-cache",
    "Last-Modified": info.mtime.toUTCString(),
    "X-Content-Type-Options": "nosniff",
  };
  const range = parseRange(request.headers.get("range"), size);
  if (range === "unsatisfiable") {
    return new Response(null, { status: 416, headers: { ...baseHeaders, "Content-Range": `bytes */${size}` } });
  }
  const start = range?.start ?? 0;
  const end = range?.end ?? size - 1;
  const headers = { ...baseHeaders, "Content-Length": String(size === 0 ? 0 : end - start + 1) };
  if (range) headers["Content-Range" as keyof typeof headers] = `bytes ${start}-${end}/${size}`;
  const status = range ? 206 : 200;
  if (!includeBody || size === 0) return new Response(null, { status, headers });
  const stream = createReadStream(filePath, { start, end });
  // Stop reading from disk when the browser aborts (e.g. seeking elsewhere).
  request.signal.addEventListener("abort", () => stream.destroy(), { once: true });
  return new Response(Readable.toWeb(stream) as ReadableStream<Uint8Array>, { status, headers });
}

export function GET(request: Request, ctx: RouteContext<"/api/videos/[id]/media">) {
  return serve(request, ctx, true);
}

export function HEAD(request: Request, ctx: RouteContext<"/api/videos/[id]/media">) {
  return serve(request, ctx, false);
}
