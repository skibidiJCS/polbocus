import { issueSignedToken } from "@vercel/blob";
import { handleUpload, handleUploadPresigned, type HandleUploadBody, type HandleUploadPresignedBody } from "@vercel/blob/client";
import { AUTH_COOKIE, verifySessionToken } from "@/lib/auth";
import { blobUploadMethod } from "@/lib/server/blob-store";
import { ALLOWED_UPLOAD_TYPES, isSessionBlobPath, SESSION_MAX_BYTES } from "@/lib/server/session";
import { rejectCrossOrigin } from "@/lib/server/session-http";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const UPLOAD_WINDOW_MS = 2 * 60 * 60_000;

/**
 * Lets the signed-in browser upload straight to the private Blob store.
 * Stores connected with Vercel's default OIDC auth use presigned URLs; a store with a
 * read-write token (e.g. local testing) uses client tokens.
 */
export async function POST(request: Request) {
  const rejected = rejectCrossOrigin(request);
  if (rejected) return rejected;
  const cookie = request.headers.get("cookie")?.split(/;\s*/).find((part) => part.startsWith(`${AUTH_COOKIE}=`))?.slice(AUTH_COOKIE.length + 1);
  if (!(await verifySessionToken(cookie))) return Response.json({ error: "Sign in first." }, { status: 401 });
  try {
    const body = (await request.json()) as HandleUploadBody | HandleUploadPresignedBody;
    if (blobUploadMethod() === "presigned") {
      const result = await handleUploadPresigned({
        request,
        body: body as HandleUploadPresignedBody,
        getSignedToken: async (pathname) => {
          // Pathnames are generated by our page: sessions/<uuid>.<ext>
          if (!isSessionBlobPath(pathname)) throw new Error("Unexpected upload path.");
          const validUntil = Date.now() + UPLOAD_WINDOW_MS;
          const token = await issueSignedToken({ pathname, operations: ["put"], validUntil, allowedContentTypes: ALLOWED_UPLOAD_TYPES, maximumSizeInBytes: SESSION_MAX_BYTES });
          return { token, urlOptions: { validUntil, allowedContentTypes: ALLOWED_UPLOAD_TYPES, maximumSizeInBytes: SESSION_MAX_BYTES, addRandomSuffix: true } };
        },
      });
      return Response.json(result);
    }
    const result = await handleUpload({
      request,
      body: body as HandleUploadBody,
      onBeforeGenerateToken: async (pathname) => {
        if (!isSessionBlobPath(pathname)) throw new Error("Unexpected upload path.");
        return { allowedContentTypes: ALLOWED_UPLOAD_TYPES, maximumSizeInBytes: SESSION_MAX_BYTES, addRandomSuffix: true, validUntil: Date.now() + UPLOAD_WINDOW_MS };
      },
    });
    return Response.json(result);
  } catch (error) {
    return Response.json({ error: error instanceof Error ? error.message : "Upload could not start." }, { status: 400 });
  }
}
